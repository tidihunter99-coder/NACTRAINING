import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { queries } from './audit-catalog.mjs';

const names = readdirSync('supabase/migrations').filter((name) => name.endsWith('.sql')).sort();
if (names.length !== 21) throw new Error('Expected exactly 21 reviewed migrations');

// The prior 15-migration candidate contains exact remote catalog guards and the
// incremental changes after the already-present baseline. Its trailing 15-step
// postconditions/COMMIT are replaced with current 21-step postconditions.
const previous = readFileSync('supabase/audit/reconciliation-candidate.sql', 'utf8');
const marker = '-- Verify exact expected catalog before committing.';
const at = previous.indexOf(marker);
if (at < 0 || previous.lastIndexOf('COMMIT;') < at) throw new Error('Prior candidate format changed');
let body = previous.slice(0, at);

const target = (name) => JSON.parse(readFileSync(`supabase/audit/mission111-target-${name}.json`, 'utf8'));
const guard = (name, query, index) => {
  const expected = JSON.stringify(target(name)).replaceAll('\\r\\n', '\\n');
  if (expected.includes(`$mission11_${index}$`)) throw new Error('Unsafe guard delimiter');
  const normalizedQuery = name === 'functions'
    ? query.replace('pg_get_functiondef(p.oid) as definition', "replace(pg_get_functiondef(p.oid), E'\\r\\n', E'\\n') as definition")
    : query;
  return `DO $mission11_guard${index}$ BEGIN
  IF (SELECT coalesce(jsonb_agg(q),'[]'::jsonb) FROM (${normalizedQuery}) q)
     IS DISTINCT FROM $mission11_${index}$${expected}$mission11_${index}$::jsonb THEN
    RAISE EXCEPTION 'Mission 11 postcondition failed: ${name}';
  END IF;
END $mission11_guard${index}$;`;
};

body += `
-- Additional prerequisites for migrations 16-21. Preserve all user data.
DO $mission11_preflight$ BEGIN
  IF to_regclass('storage.buckets') IS NULL OR to_regclass('storage.objects') IS NULL THEN
    RAISE EXCEPTION 'Storage schema missing; inspect manually';
  END IF;
  IF to_regclass('public.student_exercise_favorites') IS NOT NULL THEN
    RAISE EXCEPTION 'Favorites already exist; re-audit before running';
  END IF;
  IF EXISTS (SELECT 1 FROM storage.buckets WHERE id='nac-exercise-media') THEN
    RAISE EXCEPTION 'Media bucket already exists; re-audit before running';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects'
    AND policyname LIKE 'nac_exercise_media_%') THEN
    RAISE EXCEPTION 'NAC Storage policies already exist; re-audit before running';
  END IF;
  IF to_regclass('supabase_migrations.schema_migrations') IS NOT NULL THEN
    RAISE EXCEPTION 'Migration history appeared; re-audit before running';
  END IF;
END $mission11_preflight$;

`;
for (const name of names.slice(15)) {
  body += `-- Source: ${name}\n${readFileSync(`supabase/migrations/${name}`, 'utf8')}\n\n`;
}

body += `-- Exact catalog postconditions for all 21 local migrations.
${Object.entries(queries).map(([name, query], index) => guard(name, query, index)).join('\n\n')}

DO $mission11_storage_check$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM storage.buckets WHERE id='nac-exercise-media'
    AND public=false AND file_size_limit=26214400
    AND allowed_mime_types = ARRAY['image/jpeg','image/png','image/webp','image/avif','image/gif','video/mp4','video/webm']::text[]) THEN
    RAISE EXCEPTION 'Media bucket configuration mismatch';
  END IF;
  IF (SELECT count(*) FROM pg_policies WHERE schemaname='storage' AND tablename='objects'
    AND policyname IN ('nac_exercise_media_admin_insert','nac_exercise_media_admin_delete','nac_exercise_media_authorized_select')) <> 3 THEN
    RAISE EXCEPTION 'NAC Storage policy count mismatch';
  END IF;
  IF has_function_privilege('anon','public.write_audit_event(text,text,uuid)','EXECUTE')
    OR has_function_privilege('authenticated','public.write_audit_event(text,text,uuid)','EXECUTE') THEN
    RAISE EXCEPTION 'Unsafe audit function EXECUTE remains';
  END IF;
END $mission11_storage_check$;
COMMIT;
`;
body = body.replace('Generated by scripts/prepare-reconciliation.mjs; review before execution.',
  'Based on 4/11 catalog revalidated by ten fingerprints on 5/11. Manual project, backup and dependency checks remain mandatory.');
body = `-- HOLD: Remote execution requires verified recoverable backup, fresh remote re-audit and owner authorization.\n${body}`;
writeFileSync('supabase/audit/mission11-incremental-candidate.sql', body);
console.log('Prepared local-only 21-migration incremental candidate; remote execution is not authorized.');
